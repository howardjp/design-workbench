import { firefox, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { preview } from 'vite';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';
const directory = fileURLToPath(new URL('.', import.meta.url));
const server = await preview({ root: directory, configFile: false, preview: { host: '127.0.0.1', port: 4197, strictPort: true } });
let browser;
const checks = [];
const errors = [];
const check = name => { checks.push(name); console.log(`PASS ${name}`); };
try {
  browser = await firefox.launch({ env: { ...process.env, MOZ_DISABLE_CONTENT_SANDBOX: '1' }, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const screenshot = async name => {
    await page.evaluate(() => window.scrollTo(0, 0));
    return page.screenshot({ path: `${directory}${name}.png`, fullPage: true });
  };
  const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const axe = async name => {
    const { violations } = await new AxeBuilder({ page }).analyze();
    expect(violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([]);
    check(`axe: ${name}, zero violations`);
  };
  await page.goto('http://127.0.0.1:4197');
  await expect(page.getByRole('heading', { level: 1, name: 'All contacts' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Read contact:', exact: false })).toHaveCount(5);
  expect(await page.locator('.martlet-app').evaluate(el => getComputedStyle(el).gridTemplateColumns)).toMatch(/^240px /);
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('main')).toBeFocused();
  await noOverflow(); await screenshot('collection-light-wide'); await axe('collection light, 1366px');
  check('Actual AppShell renders side rail; native keyboard skip link focuses main');

  await page.getByRole('button', { name: /^Studio/ }).click();
  await expect(page.getByRole('button', { name: 'Read contact:', exact: false })).toHaveCount(3);
  await page.getByRole('searchbox', { name: 'Search studio' }).fill('Sam');
  await expect(page.getByRole('heading', { name: 'No matching contacts' })).toBeVisible();
  await page.getByRole('button', { name: 'Clear search', exact: true }).first().click();
  await expect(page.getByRole('searchbox')).toBeFocused();
  await page.getByRole('searchbox').fill('Ada');
  await page.getByRole('button', { name: 'Read contact: Ada Bennett' }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'Ada Bennett' })).toBeFocused();
  await screenshot('reading-light-wide'); await axe('record reading');
  await page.getByRole('button', { name: '← Back to studio' }).click();
  await expect(page.getByRole('searchbox')).toHaveValue('Ada');
  await expect(page.getByRole('button', { name: 'Read contact: Ada Bennett' })).toBeFocused();
  check('Scoped search excludes other groups; no-match recovery and reading/back retain query and focus');

  await page.getByRole('button', { name: 'Read contact: Ada Bennett' }).click();
  await page.getByRole('button', { name: 'Edit contact', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Name (required)' })).toBeFocused();
  await page.getByRole('textbox', { name: 'Name (required)' }).fill('');
  await page.getByRole('textbox', { name: 'Email (required)' }).fill('bad-address');
  await page.getByRole('button', { name: 'Save contact', exact: true }).click();
  await expect(page.getByRole('alert')).toBeFocused();
  await expect(page.getByRole('textbox', { name: 'Email (required)' })).toHaveValue('bad-address');
  await expect(page.getByRole('textbox', { name: 'Name (required)' })).toHaveAttribute('aria-invalid', 'true');
  await screenshot('editor-validation'); await axe('validation summary and field errors');
  await page.getByRole('link', { name: /Enter an email address/ }).click();
  await expect(page.getByRole('textbox', { name: 'Email (required)' })).toBeFocused();
  check('Validation retains input, names invalid fields, focuses linked error summary');

  await page.getByRole('textbox', { name: 'Name (required)' }).fill('Ada Bennett');
  await page.getByRole('textbox', { name: 'Email (required)' }).fill('ada.updated@example.test');
  await page.getByRole('textbox', { name: 'Working notes' }).fill('Updated context.\nSecond line retained.');
  await page.getByText('Demo: inspect save recovery', { exact: true }).click();
  await page.getByRole('checkbox', { name: 'Make the next save fail' }).check();
  await page.getByRole('button', { name: 'Save contact', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Saving…', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: /^Partners/ })).toBeDisabled();
  await expect(page.getByRole('alert')).toContainText('Your contact could not be saved');
  await expect(page.getByRole('alert')).toBeFocused();
  await expect(page.getByRole('textbox', { name: 'Working notes' })).toHaveValue('Updated context.\nSecond line retained.');
  await screenshot('editor-failed-save'); await axe('recoverable failed save');
  await page.getByRole('button', { name: 'Retry save', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'Ada Bennett' })).toBeFocused();
  await expect(page.getByText('ada.updated@example.test', { exact: true })).toBeVisible();
  await expect(page.getByText('Updated context.\nSecond line retained.', { exact: true })).toBeVisible();
  await expect(page.locator('.directory-status')).toHaveText('Ada Bennett saved for this session.');
  check('Pending disables controls; failed save retains draft and focuses recovery; retry commits and announces success');

  await page.getByRole('button', { name: 'Edit contact', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name (required)' }).fill('Unsaved name');
  await page.getByRole('button', { name: /^Partners/ }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Keep editing', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Name (required)' })).toBeFocused();
  await expect(page.getByRole('textbox', { name: 'Name (required)' })).toHaveValue('Unsaved name');
  await page.getByRole('button', { name: 'Cancel editing', exact: true }).click();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Name (required)' })).toHaveValue('Unsaved name');
  await page.getByRole('button', { name: 'Cancel editing', exact: true }).click();
  await page.getByRole('button', { name: 'Discard changes and continue', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'Ada Bennett' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Edit contact', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Edit contact', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name (required)' }).fill('Another unsaved name');
  await page.getByRole('button', { name: /^Partners/ }).click();
  await page.getByRole('button', { name: 'Discard changes and continue', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'Partners' })).toBeFocused();
  await expect(page.getByRole('searchbox')).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Read contact:', exact: false })).toHaveCount(2);
  check('Draft guard defaults to Keep editing; Escape/Keep retain draft; explicit discard restores saved data and completes navigation');

  await page.getByRole('button', { name: /^Volunteers/ }).click();
  await expect(page.getByRole('heading', { name: 'No contacts in this group yet' })).toBeVisible();
  await screenshot('empty-group');
  await page.getByRole('button', { name: 'View all contacts', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Read contact:', exact: false })).toHaveCount(5);
  check('Empty group has distinct explanation and working recovery');

  await page.setViewportSize({ width: 320, height: 780 });
  await noOverflow(); await screenshot('collection-light-narrow'); await axe('collection light, 320px');
  await page.getByRole('button', { name: 'Use dark mode', exact: true }).click();
  await noOverflow(); await screenshot('collection-dark-narrow'); await axe('collection dark, 320px');
  await page.getByRole('button', { name: 'Read contact: Ada Bennett' }).click();
  await noOverflow(); await screenshot('reading-dark-narrow');
  await page.getByRole('button', { name: 'Edit contact', exact: true }).click();
  const longName = 'Ada ' + 'Bennett-Laurent '.repeat(12);
  await page.getByRole('textbox', { name: 'Name (required)' }).fill(longName);
  await page.getByRole('textbox', { name: 'Working notes' }).fill('Long unbroken context: ' + 'contact'.repeat(80));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addStyleTag({ content: 'html{font-size:200%}' });
  await noOverflow(); await screenshot('editor-dark-320-large-text'); await axe('editor dark, 320px, 200% base text');
  await page.getByRole('button', { name: 'Save contact', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(longName.trim());
  await noOverflow(); await screenshot('reading-dark-320-long-text');
  await page.addStyleTag({ content: '.directory-demo{filter:grayscale(1)}.martlet-app-brand{visibility:hidden}' });
  await screenshot('reading-dark-grayscale');
  check('320px light/dark reflow, 200% text and long/unbroken content stay within viewport; reduced-motion path saves');
  expect(errors).toEqual([]);
  check('No browser page errors');
  await writeFile(`${directory}verification.json`, JSON.stringify({ browser: 'Playwright Firefox 1555', checks, pageErrors: errors, limits: ['No manual screen-reader testing', 'No real backend or durable persistence', 'No cross-browser checks', 'MCP catalogue unavailable; used bundled skill references'] }, null, 2));
} finally {
  await browser?.close();
  await new Promise(resolve => server.httpServer.close(resolve));
}
